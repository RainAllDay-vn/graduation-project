package com.gr2.noc.hypothesis.controller;

import com.gr2.noc.hypothesis.dto.create.CreateHypothesisRequest;
import com.gr2.noc.hypothesis.dto.get.HypothesisDetails;
import com.gr2.noc.hypothesis.dto.get.HypothesisSummary;
import com.gr2.noc.hypothesis.dto.update.UpdateHypothesisStatusRequest;
import com.gr2.noc.hypothesis.enums.HypothesisStatus;
import jakarta.validation.Valid;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

/**
 * REST API Contract for Incident Root Cause Hypotheses Management.
 * Manages hypotheses generated by AI or entered by NOC engineers for an incident.
 */
@RequestMapping("/api/incidents/{incidentId}/hypotheses")
public interface HypothesisApi {

    /**
     * Retrieve all hypotheses for an incident, optionally filtered by status.
     * Ordered by rank ascending (Rank 1, Rank 2, ...).
     */
    @GetMapping
    ResponseEntity<List<HypothesisSummary>> getHypotheses(
            @PathVariable String incidentId,
            @RequestParam(required = false) HypothesisStatus status
    );

    /**
     * Retrieve detailed information of a specific hypothesis, including evidence,
     * contradicting evidence, CLI verification commands, and rejection details.
     */
    @GetMapping("/{hypothesisId}")
    ResponseEntity<HypothesisDetails> getHypothesisById(
            @PathVariable String incidentId,
            @PathVariable Long hypothesisId
    );

    /**
     * Create a new hypothesis for an incident.
     */
    @PostMapping
    ResponseEntity<HypothesisDetails> createHypothesis(
            @PathVariable String incidentId,
            @Valid @RequestBody CreateHypothesisRequest request
    );

    /**
     * Update lifecycle status of a hypothesis (CONFIRMED, REJECTED, UNDER_CONSIDERATION).
     * If rejecting, a rejection reason must be provided.
     */
    @PatchMapping("/{hypothesisId}/status")
    ResponseEntity<HypothesisDetails> updateHypothesisStatus(
            @PathVariable String incidentId,
            @PathVariable Long hypothesisId,
            @Valid @RequestBody UpdateHypothesisStatusRequest request
    );

    /**
     * Delete a hypothesis by ID.
     */
    @DeleteMapping("/{hypothesisId}")
    ResponseEntity<Void> deleteHypothesis(
            @PathVariable String incidentId,
            @PathVariable Long hypothesisId
    );
}
